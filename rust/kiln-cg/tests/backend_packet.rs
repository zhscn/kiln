use kiln_cg::{packet, sexp};
use std::{path::PathBuf, process::Command};

#[test]
fn lisp_and_rust_encode_identical_indexed_requests() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let path = std::env::temp_dir().join(format!("kiln-packet-{}.lir", std::process::id()));
    struct Remove(PathBuf);
    impl Drop for Remove {
        fn drop(&mut self) {
            let _ = std::fs::remove_file(&self.0);
        }
    }
    let _remove = Remove(path.clone());
    let output = Command::new("sbcl")
        .current_dir(&root)
        .args([
            "--noinform",
            "--no-sysinit",
            "--no-userinit",
            "--non-interactive",
        ])
        .args(["--load", "tools/test-backend-packet.lisp", "--eval"])
        .arg(format!(
            "(write-packet-fixture {:?})",
            path.to_str().unwrap()
        ))
        .output()
        .expect("SBCL is required for cross-language protocol tests");
    assert!(
        output.status.success(),
        "{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    let bytes = std::fs::read(&path).unwrap();
    let program = sexp::parse_one(r#"(module "λ\"\\" (init "init") (data "init" (words -9223372036854775808 9223372036854775807)) (func "f" (vars (v12 obj)) (slots) (block b3 (return v12 1))))"#).unwrap();
    assert_eq!(packet::decode(&bytes).unwrap().program, program);
    assert_eq!(
        bytes,
        packet::encode(&program, packet::schema::KIR_PAYLOAD).unwrap()
    );
}

#[test]
fn target_description_is_current() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../lisp/backend-target.lisp");
    let expected = format!(
        ";;;; Generated by kiln-cg target-description.\n(in-package #:kiln.kir)\n(defconstant +backend-target-fingerprint+ {})\n",
        packet::target_fingerprint()
    );
    assert_eq!(
        std::fs::read_to_string(path).unwrap(),
        expected,
        "regenerate with kiln-cg target-description"
    );
}
