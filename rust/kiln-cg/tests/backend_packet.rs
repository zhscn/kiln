#[test]
fn named_fields_preserve_the_legacy_kir_program() {
    use packet::schema::*;
    for (field, offset, writable) in [
        (FIELD_CONS_CAR, 7, true),
        (FIELD_CONS_CDR, 15, true),
        (FIELD_SYMBOL_NAME, 3, true),
        (FIELD_SYMBOL_PACKAGE, 11, true),
        (FIELD_SYMBOL_FUNCTION, 19, true),
        (FIELD_SYMBOL_VALUE, 27, true),
        (FIELD_SYMBOL_TLS_INDEX, 35, true),
        (FIELD_SYMBOL_PLIST, 43, true),
        (FIELD_SYMBOL_SETF_FUNCTION, 51, true),
        (FIELD_FUNCTION_ENTRY, 3, false),
    ] {
        let legacy_store = if writable {
            format!("(store a0 {offset} a1)")
        } else {
            String::new()
        };
        let named_store = if writable {
            format!("(field-store {field} a0 a1)")
        } else {
            String::new()
        };
        let module = |body| {
            format!(
                "(module \"fields\" (init \"init\") (data \"init\" (words 2 (func \"body\"))) (func \"body\" (vars (v obj)) (slots) (block b {body} (return v 1))))"
            )
        };
        let old = module(format!("(set v (load a0 {offset})) {legacy_store}"));
        let new = module(format!("(set v (field-load {field} a0)) {named_store}"));
        let old = kiln_cg::kir::parse_module(&sexp::parse_one(&old).unwrap()).unwrap();
        let new = sexp::parse_one(&new).unwrap();
        let new = packet::load(&packet::encode(&new, KIR_PAYLOAD).unwrap()).unwrap();
        assert_eq!(format!("{old:?}"), format!("{new:?}"));
    }
}

#[test]
fn dynamic_transfer_slots_expand_to_context_accesses() {
    let module = |body| format!("(module \"transfer\" (init \"init\") (data \"init\" (words 2 (func \"body\"))) (func \"body\" (vars (v obj) (i raw)) (slots) (block b {body} (return v 1))))");
    let old = module("(set v (load (add ctx (shl i 3)) 88)) (store (add ctx (shl i 3)) 88 a0)".to_string());
    let new = module("(set v (transfer-ref-dynamic i)) (transfer-set-dynamic i a0)".to_string());
    let old = kiln_cg::kir::parse_module(&sexp::parse_one(&old).unwrap()).unwrap();
    let new = sexp::parse_one(&new).unwrap();
    let new = packet::load(&packet::encode(&new, packet::schema::KIR_PAYLOAD).unwrap()).unwrap();
    assert_eq!(format!("{old:?}"), format!("{new:?}"));
}

#[test]
fn fixed_transfer_slots_preserve_kir_and_check_bounds() {
    let module = |body| format!("(module \"transfer\" (init \"init\") (data \"init\" (words 2 (func \"body\"))) (func \"body\" (vars (v obj)) (slots) (block b {body} (return v 1))))");
    for index in [0, 1, 1020] {
        let offset = 88 + index * 8;
        let old = module(format!("(set v (load ctx {offset})) (store ctx {offset} a0)"));
        let new = module(format!("(set v (transfer-ref {index})) (transfer-set {index} a0)"));
        let old = kiln_cg::kir::parse_module(&sexp::parse_one(&old).unwrap()).unwrap();
        let new = sexp::parse_one(&new).unwrap();
        let new = packet::load(&packet::encode(&new, packet::schema::KIR_PAYLOAD).unwrap()).unwrap();
        assert_eq!(format!("{old:?}"), format!("{new:?}"));
    }
    for index in [-1_i64, 1021, i64::MAX] {
        for body in [format!("(set v (transfer-ref {index}))"), format!("(transfer-set {index} a0)")] {
            assert!(kiln_cg::kir::parse_module(&sexp::parse_one(&module(body)).unwrap()).is_err());
        }
    }
}

